package ar.uba.fi.cb100.clases.a2026.c02.s03.herencia;

public class Casa {
//ATRIBUTOS DE CLASE --------------------------------------------------------------------------------------
//ATRIBUTOS -----------------------------------------------------------------------------------------------

    private Animal[] mascotas;

//CONSTRUCTORES -------------------------------------------------------------------------------------------

    public Casa(int cantidadMaxima) {
        this.mascotas = new Animal[cantidadMaxima];
    }

//METODOS ABSTRACTOS --------------------------------------------------------------------------------------
//METODOS DE CLASE ----------------------------------------------------------------------------------------
//METODOS GENERALES ---------------------------------------------------------------------------------------
//METODOS DE COMPORTAMIENTO -------------------------------------------------------------------------------

    public void adoptarMascota(Animal mascota) {
        for (int i = 0; i < mascotas.length; i++) {
            if (mascotas[i] == null) {
                mascotas[i] = mascota;
                return;
            }
        }
    }

//GETTERS SIMPLES -----------------------------------------------------------------------------------------
//SETTERS SIMPLES -----------------------------------------------------------------------------------------
}
